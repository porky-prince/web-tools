import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const defaultSrcDir = fileURLToPath(new URL('../src', import.meta.url));
export const sourceEntry = fileURLToPath(
  new URL('../src/index.ts', import.meta.url)
);

function collectSourceFiles(dir, sourceEntryPath) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((dirent) => {
    const path = join(dir, dirent.name);

    if (dirent.isDirectory()) {
      return collectSourceFiles(path, sourceEntryPath);
    }

    if (
      path === sourceEntryPath ||
      !dirent.isFile() ||
      !dirent.name.endsWith('.ts') ||
      dirent.name.endsWith('.d.ts')
    ) {
      return [];
    }

    return [path];
  });
}

function toExportPath(srcDir, file) {
  return `./${relative(srcDir, file).replace(/\\/g, '/').replace(/\.ts$/, '')}`;
}

function isExported(node) {
  return (
    ts.canHaveModifiers(node) &&
    ts
      .getModifiers(node)
      ?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
  );
}

function getExportedNames(file) {
  const sourceFile = ts.createSourceFile(
    file,
    readFileSync(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true
  );
  const names = new Set();

  function addDeclarationName(node) {
    if (node.name?.kind === ts.SyntaxKind.Identifier) {
      names.add(node.name.text);
    }
  }

  sourceFile.forEachChild((node) => {
    if (ts.isExportDeclaration(node) && node.exportClause) {
      if (ts.isNamedExports(node.exportClause)) {
        for (const element of node.exportClause.elements) {
          names.add(element.name.text);
        }
      }
      return;
    }

    if (ts.isVariableStatement(node) && isExported(node)) {
      for (const declaration of node.declarationList.declarations) {
        addDeclarationName(declaration);
      }
      return;
    }

    if (
      isExported(node) &&
      (ts.isClassDeclaration(node) ||
        ts.isFunctionDeclaration(node) ||
        ts.isInterfaceDeclaration(node) ||
        ts.isTypeAliasDeclaration(node) ||
        ts.isEnumDeclaration(node))
    ) {
      addDeclarationName(node);
    }
  });

  return [...names];
}

function validateUniqueExports(srcDir, files) {
  const exportedFrom = new Map();

  for (const file of files) {
    const exportPath = toExportPath(srcDir, file);

    for (const name of getExportedNames(file)) {
      const existingPath = exportedFrom.get(name);

      if (existingPath && existingPath !== exportPath) {
        throw new Error(
          `Duplicate export name '${name}' found in ${existingPath} and ${exportPath}.`
        );
      }

      exportedFrom.set(name, exportPath);
    }
  }
}

export function generateSourceEntry(options = {}) {
  const srcDir = options.srcDir ?? defaultSrcDir;
  const sourceEntryPath = options.sourceEntry ?? sourceEntry;
  const sourceFiles = collectSourceFiles(srcDir, sourceEntryPath);

  validateUniqueExports(srcDir, sourceFiles);

  const exports = sourceFiles
    .map((file) => toExportPath(srcDir, file))
    .sort()
    .map((path) => `export * from '${path}';`);
  const content = [
    '// This file is generated by packages/es-stl/scripts/generate-source-entry.mjs.',
    ...exports,
    '',
  ].join('\n');

  if (
    existsSync(sourceEntryPath) &&
    readFileSync(sourceEntryPath, 'utf8') === content
  ) {
    return;
  }

  mkdirSync(dirname(sourceEntryPath), { recursive: true });
  writeFileSync(sourceEntryPath, content);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  generateSourceEntry();
}
